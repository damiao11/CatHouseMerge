def main():
    scenes = {s["id"]: {"day": s["day"], "kind": s["kind"],
                        "lines": [{"who": l["who"], "text": l["text"]} for l in s["lines"]]}
              for s in S}
    data = {"version": 1, "scenes": scenes,
            "almanac": [{"cat": c, "title": t, "text": x} for c, t, x in ALMANAC],
            "letters": [{"title": t, "text": x} for t, x in LETTERS]}
    with open("dialogue.json", "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)

    total = sum(len(l["text"]) for s in S for l in s["lines"])
    total += sum(len(x) for _, _, x in ALMANAC) + sum(len(x) for _, x in LETTERS)

    out = []
    for day in range(1, 25):
        out.append(f"## 第 {day} 天 · {ROOM[day]}\n")
        for s in [x for x in S if x["day"] == day]:
            label = {"intro": "开场", "outro": "收尾", "cat": "猫的请求",
                     "choice": "选择"}[s["kind"]]
            out.append(f"**{label}**\n")
            for l in s["lines"]:
                out.append(f"**{NAME[l['who']]}**：{l['text']}  ")
            out.append("")
    out.append("\n## 猫图鉴（6 篇）\n")
    for c, t, x in ALMANAC:
        out.append(f"**{NAME[c]} · {t}**\n\n{x}\n")
    out.append("\n## 三封信\n")
    for t, x in LETTERS:
        out.append(f"**{t}**\n\n{x}\n")
    with open("body.md", "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("scenes:", len(scenes), "chars:", total,
          "lines:", sum(len(s["lines"]) for s in S))

main()
